    page.set_viewport_size({'width':390,'height':844});page.locator('[data-back-top]').click();page.wait_for_timeout(80)
    page.screenshot(path=str(OUT / 'mobile.png'))
    for kind in ['library','toc','notes']:
        page.locator(f'.floating-dock [data-drawer="{kind}"]').click()
        check(f'Mobile {kind} drawer opens', page.locator('#drawer').evaluate('(e)=>e.open'))
        check(f'Mobile {kind} drawer contains live DOM', page.locator('#drawer-body > *').count() == 1)
        page.keyboard.press('Escape');page.wait_for_timeout(20)
        check(f'Mobile {kind} restores original DOM', page.locator('.workspace > #library').count() == 1 and page.locator('.workspace > #right-rail').count() == 1)
