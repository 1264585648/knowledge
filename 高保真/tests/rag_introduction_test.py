    restored.locator('#notes-tab').click()
    check('Serialized notes restore in a fresh document', restored.locator('.note-item').count() == 2)
    restored.locator('.note-item').first.get_by_role('button',name='删除',exact=True).click()
    check('Confirmed delete removes note', restored.locator('.note-item').count() == 1)
