    check('Mobile chapter navigation closes drawer', not page.locator('#drawer').evaluate('(e)=>e.open'))
    page.locator('.floating-dock [data-drawer="notes"]').click()
    page.set_viewport_size({'width':1586,'height':992});page.wait_for_timeout(80)
    check('Widening viewport restores right rail', not page.locator('#drawer').evaluate('(e)=>e.open') and page.locator('.workspace > #right-rail').count() == 1)
    broken=load(context,{KEY+'notes':'{invalid'})
    broken.locator('#notes-tab').click();broken.locator('#note-input').fill('不能覆盖旧数据');broken.locator('#save-note').click()
    check('Corrupt storage remains intact', broken.evaluate('__store["'+KEY+'notes"]') == '{invalid')
    check('Corruption warning shown', not broken.locator('#storage-warning').evaluate('(e)=>e.hidden'))
    broken.close()
